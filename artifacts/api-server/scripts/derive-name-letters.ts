/**
 * Regenerates `lib/api-zod/src/personalNameLetters.generated.ts`: the letters
 * the name rule admits, derived from the shipped caption fonts. Run after a
 * caption face is added, removed or replaced:
 *
 *   npx tsx artifacts/api-server/scripts/derive-name-letters.ts
 *
 * `nameLetterDerivation.test.ts` fails until the file matches the fonts.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CAPTION_FONTS } from "@workspace/api-zod";
import { deriveNameLetters, toRanges } from "../src/lib/fontCoverage";

const here = path.dirname(fileURLToPath(import.meta.url));
const fonts = path.resolve(here, "..", "src", "assets", "fonts");
const out = path.resolve(here, "..", "..", "..", "lib", "api-zod", "src", "personalNameLetters.generated.ts");

const hex = (cp: number) => `0x${cp.toString(16).toUpperCase().padStart(4, "0")}`;
const letters = deriveNameLetters(CAPTION_FONTS.map((f) => fs.readFileSync(path.join(fonts, f.file))));
const body = toRanges(letters).map(([a, b]) => `  [${hex(a)}, ${hex(b)}],`).join("\n");

fs.writeFileSync(out, `/**
 * GENERATED by artifacts/api-server/scripts/derive-name-letters.ts from the
 * shipped caption fonts. Do not edit by hand: change a font, then re-run it.
 *
 * The letters a personal name may hold: every Latin-script letter that all
 * caption faces draw, in both cases (${letters.length} letters).
 *
 * @purpose The name rule's admitted letters as code-point ranges, derived from the caption font files.
 * @subsystem accounts-auth
 */
export const PERSONAL_NAME_LETTER_RANGES: readonly (readonly [number, number])[] = [
${body}
];
`);
console.log(`${letters.length} letters written to ${path.relative(process.cwd(), out)}`);
